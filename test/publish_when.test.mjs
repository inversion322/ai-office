import { test } from 'node:test';
import assert from 'node:assert/strict';
import { parseWhen, mskToMs, fmtMsk, isCancelWhen, mskParts } from '../scripts/publish_when.mjs';

const NOW = mskToMs(2026, 10, 22, 3, 0);          // четверг, 22.10.2026, 03:00 МСК: время из просьбы Ника
const ok = (s, now = NOW) => { const r = parseWhen(s, now); assert.equal(r.ok, true, `«${s}»: ${r.error}`); return r.text; };
const bad = (s, re, now = NOW) => { const r = parseWhen(s, now); assert.equal(r.ok, false, `«${s}» не должно приниматься`); assert.match(r.error, re); };

test('завтра в нужное время: «завтра 18:00» и вариации записи', () => {
  for (const s of ['завтра 18:00', 'Завтра в 18:00', 'завтра в 18', 'завтра 18.00', 'завтра 18:00 по Москве', 'завтра, 6 вечера', 'завтра в 6 вечера', 'завтра 18ч00']) assert.equal(ok(s), '23.10.2026 18:00', s);
  assert.equal(ok('завтра 9 утра'), '23.10.2026 09:00'); assert.equal(ok('завтра в 12 дня'), '23.10.2026 12:00'); assert.equal(ok('завтра в 12 ночи'), '23.10.2026 00:00');
});
test('сегодня, послезавтра, дата и день недели', () => {
  assert.equal(ok('сегодня 20:30'), '22.10.2026 20:30'); assert.equal(ok('послезавтра 9:15'), '24.10.2026 09:15');
  assert.equal(ok('25.10 19:00'), '25.10.2026 19:00'); assert.equal(ok('25.10.2026 в 19:30'), '25.10.2026 19:30'); assert.equal(ok('25 октября в 19:00'), '25.10.2026 19:00'); assert.equal(ok('1 ноября 8:00'), '01.11.2026 08:00');
  assert.equal(ok('в субботу 11:00'), '24.10.2026 11:00'); assert.equal(ok('в понедельник в 10'), '26.10.2026 10:00'); assert.equal(ok('в четверг 18:00'), '22.10.2026 18:00', 'четверг сегодня и 18:00 ещё впереди');
});
test('точка в времени: «18.00» после слова дня или «в» это время, голое «18.00» и «25.10» это дата', () => {
  assert.equal(ok('завтра 18.00'), '23.10.2026 18:00'); assert.equal(ok('в субботу в 11.30'), '24.10.2026 11:30'); assert.equal(ok('25.10 18.00'), '25.10.2026 18:00', 'дата и время через точку');
  assert.equal(ok('25.10 19:00'), '25.10.2026 19:00');
});
test('время без дня: ближайшее такое время, с запасом десять минут', () => {
  assert.equal(ok('18:00'), '22.10.2026 18:00');                                   // сейчас 03:00: сегодня 18:00 ещё впереди
  assert.equal(ok('03:05'), '23.10.2026 03:05', 'через 5 минут: меньше запаса, значит завтра');
  assert.equal(ok('02:00'), '23.10.2026 02:00');
  assert.equal(ok('18:00', mskToMs(2026, 10, 22, 19, 0)), '23.10.2026 18:00');
});
test('«через N часов / минут»', () => {
  assert.equal(ok('через 3 часа'), '22.10.2026 06:00'); assert.equal(ok('через 40 минут'), '22.10.2026 03:40'); assert.equal(ok('через полтора часа'), '22.10.2026 04:30'); assert.equal(ok('через 2 ч'), '22.10.2026 05:00');
  bad('через 5 минут', /меньше чем через 10 минут/);
});
test('граница суток и год: 31.12 → 01.01, прошедшая дата уходит на следующий год', () => {
  assert.equal(ok('завтра 00:30', mskToMs(2026, 12, 31, 20, 0)), '01.01.2027 00:30');
  assert.equal(ok('1.10 12:00'), '01.10.2027 12:00', 'дата без года, уже прошедшая: следующий год');
  bad('29.02 12:00', /Такой даты нет/, mskToMs(2027, 12, 1, 10, 0));        // 2027 не високосный, угадывать 2028 не будем
  assert.equal(ok('29.02.2028 12:00', mskToMs(2027, 12, 1, 10, 0)), '29.02.2028 12:00');
});
test('отказы с понятной причиной: прошлое, слишком близко, нет времени, несуществующая дата, дальше года', () => {
  bad('сегодня 02:00', /уже прошло/); bad('сегодня 03:05', /меньше чем через 10 минут/); bad('завтра', /время суток/); bad('', /Не вижу времени/); bad('привет', /время суток/);
  bad('31.02 18:00', /Такой даты нет/); bad('32.10 18:00', /Такой даты нет/); bad('25.13 18:00', /Такой даты нет/); bad('25.10.2028 18:00', /дальше чем через год|Слишком далеко/);
});
test('московское время не зависит от пояса ПК: 03:00 МСК = 00:00 UTC', () => {
  assert.equal(new Date(NOW).toISOString(), '2026-10-22T00:00:00.000Z'); const r = parseWhen('завтра 18:00', NOW); assert.equal(r.at.toISOString(), '2026-10-23T15:00:00.000Z');
  assert.deepEqual(mskParts(NOW), { y: 2026, m: 10, d: 22, h: 3, min: 0 }); assert.equal(fmtMsk(NOW), '22.10.2026 03:00');
});
test('«отмена» и подобное не принимается за время и отменяет ожидание', () => {
  for (const s of ['отмена', 'Отмена!', 'не надо', 'передумал', 'нет', 'стоп']) assert.equal(isCancelWhen(s), true, s);
  for (const s of ['завтра 18:00', 'нет, лучше завтра в 18', 'отмена публикации сегодня в 20']) assert.equal(isCancelWhen(s), false, s);
});

test('fmtMsk принимает миллисекунды, Date и ISO-строку одинаково (раньше ISO давал «NaN.NaN.NaN»), мусор не молчит', () => {
  const ms = mskToMs(2026, 10, 23, 18, 0); assert.equal(fmtMsk(ms), '23.10.2026 18:00'); assert.equal(fmtMsk(new Date(ms)), '23.10.2026 18:00'); assert.equal(fmtMsk(new Date(ms).toISOString()), '23.10.2026 18:00'); assert.equal(fmtMsk(String(ms)), '23.10.2026 18:00');
  assert.throws(() => fmtMsk('не время'), /не удалось разобрать время/); assert.throws(() => fmtMsk(undefined), /не удалось разобрать время/); assert.equal(mskParts('2026-10-23T15:00:00.000Z').h, 18, 'UTC 15:00 = МСК 18:00');
});

test('«вчера» и «позавчера» не превращаются молча в ближайшее время', () => {
  bad('вчера 12:00', /прошедший день/); bad('позавчера в 9', /прошедший день/); bad('вчера', /прошедший день/);
  assert.equal(ok('в пятницу 12:00'), '23.10.2026 12:00', 'слово «вчера» внутри других слов не мешает: пятница обычная');
});
