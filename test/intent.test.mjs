import { test } from 'node:test';
import assert from 'node:assert/strict';
import { classifyAnswer as c, quickPick, topicMentioned, stripButtonTalk, topicRequest, formatSwitch as fsw } from '../server/lib_intent.mjs';

test('да: короткие утверждения без уточнения', () => {
  for (const x of ['Да', 'да!', 'Да, сделать', 'ок', 'Окей', 'давай', 'Да-да', 'делай', 'Да, пожалуйста', 'согласен', 'подтверждаю', '+', 'Да, да, сделайте', 'Делаем', 'Утверждаю', 'утверждаю!', 'Делаем, запускай']) assert.deepEqual(c(x), { kind: 'yes', extra: '' }, x);
});
test('да с уточнением: хвост сохраняется дословно', () => {
  assert.deepEqual(c('Да, про 10000 шагов'), { kind: 'yes', extra: 'про 10000 шагов' });
  assert.deepEqual(c('ок, хук поярче'), { kind: 'yes', extra: 'хук поярче' });
});
test('нет: короткий отказ', () => { for (const x of ['Нет', 'нет!', 'не надо', 'нет, не делай', 'Отмена', 'стоп', 'не нужно', 'не сейчас']) assert.deepEqual(c(x), { kind: 'no', extra: '' }, x); });
test('двусмысленное не разбирается: уходит Капитану', () => {
  for (const x of ['Нет, давай #2', 'Да, но сначала другую', 'да, только короче', 'Ролик нужен более динамичный', 'не знаю, может другую тему?', '', 'да но не сегодня а завтра и вообще потом всё обсудим ладно хорошо отлично']) assert.equal(c(x).kind, null, x);
});
test('выбор темы числом', () => {
  for (const [x, n] of [['4', 4], ['#4', 4], ['№ 4', 4], ['тему 4', 4], ['Выбираем тему #4', 4], ['выбираю 12', 12], ['давай номер 3', 3], ['Бери #5!', 5]]) assert.equal(quickPick(x), n, x);
  for (const x of ['тему 4, но динамичнее', 'у меня 4 идеи', 'Выбираем про шаги', '10000 шагов', '']) assert.equal(quickPick(x), null, x);
});
test('тема названа: по номеру или слову из названия', () => {
  const T = 'Нужно ходить ровно десять тысяч шагов в день?';
  assert.equal(topicMentioned('Выбираем тему #4', 4, T), true); assert.equal(topicMentioned('давай про шагов', 9, T), true); assert.equal(topicMentioned('про 10000 шагов', 9, T), true);
  assert.equal(topicMentioned('сделай что-нибудь', 4, T), false); assert.equal(topicMentioned('тема 14', 4, T), false);
});
test('из ответа модели вырезаются фразы про кнопку и подтверждение', () => {
  assert.equal(stripButtonTalk('Ник, понял: тема #4. Подтвердите кнопкой, и Ксения возьмёт её. Балл 77.'), 'Ник, понял: тема #4. Балл 77.');
  assert.equal(stripButtonTalk('Нажмите кнопку.'), '');
});

test('«тема» как просьба подобрать темы: слово в начале или просьба со словом «тема», пожелание сохраняется', () => {
  for (const x of ['тема', 'Темы', 'темы!', 'тема?', 'Тему', 'подбери темы', 'Подбери тему для видео', 'найди темы для видео', 'дай темы', 'давай темы', 'нужна тема', 'нужны темы на завтра', 'хочу новые темы', 'ещё темы', 'другие темы пожалуйста', 'предложи тему', 'скинь пару тем', 'подберёшь темы?', 'темы для видео']) assert.deepEqual(topicRequest(x), { hint: '' }, x);
  assert.deepEqual(topicRequest('тема: про сон и стресс'), { hint: 'про сон и стресс' });
  assert.deepEqual(topicRequest('Темы про питание'), { hint: 'Темы про питание' });
  assert.deepEqual(topicRequest('подбери темы про витамины и иммунитет'), { hint: 'подбери темы про витамины и иммунитет' });
  assert.deepEqual(topicRequest('нужна тема про сахар, только без лечебных советов'), null, '«без»: уточнение с отрицанием уходит Капитану, пожелание не потеряется');
});
test('«тема» не просьба: выбор темы, оценка, вопрос, ответ на карточку, другой канал, длинный разговор', () => {
  for (const x of ['тема 4', 'выбираем тему #4', 'тему 4, но динамичнее', 'давай эту тему', 'да, тема про шаги', 'тема понравилась', 'тема отличная', 'тема уже в работе?', 'какие темы есть?', 'что за тема?', 'отклони тему', 'утверждаю тему', 'не надо тем', 'нет, другую тему не нужно', 'выбери тему сам', 'подбери темы для канала про путешествия', 'темы для блога про ИИ', 'сценарий по теме переделай', 'ок', 'привет', '', 'у меня 4 идеи для тем'])
    assert.equal(topicRequest(x), null, x);
  assert.equal(topicRequest('тема ' + 'слово '.repeat(30)), null, 'длинное сообщение: обычный разговор');
});
test('название предложенной темы в сообщении значит выбор, а не просьбу; но «ещё темы» при открытом списке остаётся просьбой', () => {
  const scored = [{ id: 7, title: 'Кофе обезвоживает организм?' }, { id: 8, title: 'Нужно ходить десять тысяч шагов в день?' }];
  assert.equal(topicRequest('давай тему про кофе', { scored }), null); assert.equal(topicRequest('беру тему про шагов', { scored }), null);
  assert.deepEqual(topicRequest('ещё темы', { scored }), { hint: '' }); assert.deepEqual(topicRequest('подбери темы про сон', { scored }), { hint: 'подбери темы про сон' });
});

// Переключатель форматов роликов (решение Ника 2026-10-26)
test('форматы: «только A» в разных формулировках, включая настоящие слова Ника', () => {
  for (const x of ['выставь VARIANT_FORMATS=A, пока нужны видео только по данному формату', 'VARIANT_FORMATS=A', 'variant_formats: a', 'Пока сделай так, чтобы монтировался только формат А', 'нужен только формат А',
    'оставь только формат A', 'делай только формат а', 'только A', 'Только А', 'монтируй только вариант A', 'пока только формат A, остальные не нужны'])
    assert.deepEqual(fsw(x), { only: ['A'] }, x);
});
test('форматы: «только A и B», VARIANT_FORMATS=A,B,C — набор задаётся целиком', () => {
  assert.deepEqual(fsw('только формат A и B'), { only: ['A', 'B'] }); assert.deepEqual(fsw('VARIANT_FORMATS=A,B,C'), { only: ['A', 'B', 'C'] });
  assert.deepEqual(fsw('только форматы А и С'), { only: ['A', 'C'] }); assert.deepEqual(fsw('VARIANT_FORMATS=B'), { only: ['A', 'B'] });
});
test('форматы: «B и C не нужны» выключает оба, русские Б и С понимаются', () => {
  for (const x of ['варианты B и C не нужны', 'вариации Б и С пока не нужны', 'отключи варианты B и C', 'без вариантов B и C', 'B и C не нужны', 'убери форматы B и C', 'выключи все варианты', 'отключи варианты', 'варианты пока не нужны'])
    assert.deepEqual(fsw(x), { off: x.includes('Б') || /B|C/.test(x) ? ['B', 'C'] : ['B', 'C'] }, x);
});
test('форматы: включение — «включи B и C», «верни все три формата», «включи формат B»', () => {
  for (const x of ['включи B и C', 'Включи варианты B и C', 'верни все три формата', 'верни варианты', 'включи все варианты', 'снова все три формата', 'делай все три формата', 'добавь форматы B и C'])
    assert.deepEqual(fsw(x), { on: ['B', 'C'] }, x);
  assert.deepEqual(fsw('включи формат B'), { on: ['B'] }); assert.deepEqual(fsw('добавь формат С'), { on: ['C'] });
});
test('форматы: вопрос о состоянии', () => {
  for (const x of ['какие форматы сейчас включены?', 'какие варианты сейчас монтируются', 'что сейчас с форматами B и C: включены?']) assert.deepEqual(fsw(x), { status: true }, x);
});
test('форматы: НЕ срабатывает на то, что настройкой не является', () => {
  for (const x of ['убери вариант C', 'убери вариант B', 'Утвердить все три', 'утверждаю', 'давай варианты названий', 'покажи варианты', 'сделай только в телеграм', 'делай только с фактами', 'только в одном формате?',
    'убери вариант C у темы 109', 'ролик 126 в формате B готов?', 'почему не включены B и C', 'включи музыку', 'верни название как было', 'варианты названий не нужны', 'отключи варианты названий',
    'отключи эти варианты', 'отключи варианты для этой темы', 'убери данные варианты', 'формат А мне нравится', 'вариант B лучше', 'Правка: в формате B убрать лупу', 'подбери темы про сон', 'Да', 'нет', 'делай все три сцены по очереди?'])
    assert.equal(fsw(x), null, x);
  assert.equal(fsw(''), null); assert.equal(fsw('только формат A '.repeat(30)), null);
});
