// Раздел «формат этого ролика» для задания монтажёру. Для A ничего не добавляется (задание уже написано под «Ленту»).
// Для B и C раздел ПЕРЕКРЫВАЕТ требования формата A про динамику, а общие правила (длина, зона, призыв, вердикт, библиотека, vizavi, шляпа, звук) остаются.
import fs from 'node:fs';
import path from 'node:path';
import { FORMATS } from './variants.mjs';

export function formatSection(fmt, root, { skeptic } = {}) {
  if (!fmt || fmt === 'A' || !FORMATS[fmt]) return '';
  const spec = path.join(root, FORMATS[fmt].spec); let body = '';
  try { body = fs.readFileSync(spec, 'utf8').trim(); } catch { body = `(нет файла ${FORMATS[fmt].spec}: прочитай его сам, он обязателен)`; }
  const rel = FORMATS[fmt].spec;
  return `## ФОРМАТ ЭТОГО РОЛИКА: ${fmt} «${FORMATS[fmt].name}» (ЭТОТ РАЗДЕЛ ГЛАВНЕЕ ТРЕБОВАНИЙ ФОРМАТА A НИЖЕ И ВЫШЕ)
Это один из трёх роликов на ОДНУ тему, которые монтируют параллельно три монтажёра: у каждого свой формат, хук, текст и концовка (решение Ника 2026-10-21). Всё про формат A «Лента» в этом задании (цветные поля на весь экран, гигантские слова, шторки, «новая картинка каждые 1-1,5 с», 28+ резких смен, прочитать DYNAMICS.md как главное требование) к этому ролику НЕ относится: вместо него действует спецификация ниже (${rel}); ворота проверят ролик по профилю формата ${fmt}, а не A. Без изменений остаются: длина ≤ 59 с, безопасная зона, призыв подписаться, вердикт только в конце, шляпа утки, звук, «библиотека прежде всего», vizavi-motion с раскадровкой и журналом, формат файла, лимит кругов рендера.${skeptic ? `\nРеплики «Скептика» (дословно, по одной на абзац): ${skeptic}` : ''}

${body}

`;
}
