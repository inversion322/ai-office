// Эксперименты над роликами (решение Ника 2026-10-29): правило канала нарушается намеренно на ОДНОМ ролике, чтобы сравнить результат с базой.
// Первый эксперимент — «verdict_first» («ответ вперёд»): вердикт звучит в первые 3-5 секунд вместо конца (аудит конкурентов: у роликов с высокими
// просмотрами ответ в начале; у нас он на 69-75% хронометража, просмотры 780-1 720 при любой теме). Обещание слова и призыв остаются как есть.
// Пометка живёт в experiment.json рядом со сценарием (smm/runs/video_N) и копируется в проект монтажа (video/dosieNN): по ней
//   - сценарий не отклоняется за вердикт в начале (script_style.verdictIssues выключается для этого ролика),
//   - вердикт-ворота монтажа (check_verdict_label) этот ролик пропускают,
//   - Ксения, Вера и Кирилл получают в задании прямое исключение из правила «вердикт только в конце»,
//   - аналитик (Семён) знает, что у ролика не обычная схема, и сравнивает его с базой отдельно.
// Включение: server/data/settings.json -> { "nextExperiment": "verdict_first" }. Берётся ОДИН раз первым же новым сценарием и стирается из настроек.
import fs from 'node:fs';
import path from 'node:path';
import { readSettings, writeSettings, SETTINGS_FILE } from './variants.mjs';

export const EXPERIMENTS = {
  verdict_first: { title: 'ответ вперёд', short: 'вердикт в первые секунды, обещание слова после него, призыв в конце как обычно' },
};
export const isExperiment = (name) => Object.prototype.hasOwnProperty.call(EXPERIMENTS, name);
const file = (dir) => path.join(dir, 'experiment.json');

/** Имя эксперимента ролика или null. Для английской версии (…_en) смотрит и в проект-оригинал. */
export function getExperiment(dir) {
  if (!dir) return null;
  const dirs = [dir]; if (/_en$/.test(String(dir))) dirs.push(String(dir).replace(/_en$/, ''));
  for (const d of dirs) { try { const j = JSON.parse(fs.readFileSync(file(d), 'utf8')); if (j && isExperiment(j.name)) return j.name; } catch {} }
  return null;
}
export function setExperiment(dir, name) {
  if (!isExperiment(name)) throw new Error('неизвестный эксперимент: ' + name);
  fs.mkdirSync(dir, { recursive: true }); fs.writeFileSync(file(dir), JSON.stringify({ name, ts: Date.now() }, null, 1), 'utf8');
}
/** Берёт эксперимент, заказанный Ником для следующего ролика, и стирает его из настроек (срабатывает один раз). */
export function takeNextExperiment(settingsFile = SETTINGS_FILE()) {
  const s = readSettings(settingsFile), name = s && s.nextExperiment;
  if (!name) return null;
  writeSettings({ nextExperiment: undefined }, settingsFile);
  return isExperiment(name) ? name : null;
}

const FIRST = 'Первая фраза по-прежнему про тему или про вещь зрителя (до 1,5 с).';
/** Блок задания сценаристу (Ксения). */
export function experimentTaskBlock(name) {
  if (name !== 'verdict_first') return '';
  return `ЭКСПЕРИМЕНТ «ОТВЕТ ВПЕРЁД» (решение Ника 2026-10-29, один ролик для проверки; для ЭТОГО ролика правило «вердикт только в конце» и «в хуке нет вердикта» из твоих инструкций НЕ действует, автопроверка вердикта в начале выключена). Устройство абзаца 1: ${FIRST} Вторая фраза — ОТВЕТ простыми словами за первые 3-5 секунд: что оказалось на самом деле («Нет: эта цифра не пережила пересчёта», «Работает, но не так, как говорят»). Ответ это обычная фраза, а не ярлык: без выкриков «миф!», «ложь!», «фейк!». Сразу за ответом обещание слова по формуле Ника: «Почему? Досмотри до конца. Там же будет слово для бесплатного файла с тридцатью самыми популярными мифами.» (всё это в абзаце 1; правила про слово и про середину те же). Дальше история отвечает на вопрос «почему так» и «кто ошибся»: зритель уже знает «что», держи его на «как так вышло»; каждый абзац приносит новое число или поворот и не пересказывает ответ. Последний абзац НЕ открывает ответ заново, а замыкает историю деталью или числом из хука (bookend). Длина, число абзацев, выжимка без цитат и все остальные правила без изменений. `;
}
/** Примечание для проверяющей (Вера). */
export function experimentCheckNote(name) {
  if (name !== 'verdict_first') return '';
  return `\nЭКСПЕРИМЕНТ «ОТВЕТ ВПЕРЁД» (Ник, 2026-10-29): в этом сценарии ответ звучит в первых абзацах намеренно; правило «вердикт только в конце» к нему не применяется, не возвращай сценарий за это. Остальные проверки (факты, выжимка, честность оговорок, формула обещания слова) без изменений. Проверь только, что ответ в начале не подаётся сильнее, чем позволяют источники.`;
}
/** Для брифа Кирилла (и правок): заменяет раздел «Вердикт только в конце» на исключение. Без эксперимента возвращает текст как есть. */
export function applyExperimentToBrief(text, name) {
  if (name !== 'verdict_first') return text;
  const repl = `## ЭКСПЕРИМЕНТ «ОТВЕТ ВПЕРЁД» вместо правила «вердикт только в конце» (решение Ника 2026-10-29; для этого ролика вердикт-ворота выключены; переопределяет DESIGN.md и SCRIPT_CRAFT.md)
Ответ звучит в озвучке в первые секунды. На экране он показан обычной крупной подписью из сценария, без красного штампа «МИФ?»/«ПРАВДА», без метки рубрики и без плашки-ярлыка: ярлык остаётся только в сцене вердикта ближе к концу, если она есть. Остальные правила (безопасная зона, динамика, призыв с кодовым словом, библиотека) те же. В RESULT.md одной строкой отметь, как показан ответ в первых секундах.
`;
  const re = /## Вердикт только в конце[^\n]*\n[\s\S]*?(?=\n## |$)/;
  return re.test(text) ? text.replace(re, () => repl) : text;
}
