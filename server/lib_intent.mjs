// Разбор коротких ответов Ника без модели: «да», «нет», «#4», «выбираем тему 4».
// Зачем: раньше любое сообщение шло к Капитану-модели, и на «Да» он отвечал «нажмите кнопку» и присылал ещё одну карточку подтверждения (4 карточки подряд,
// Ник жал «Да, сделать» на каждой, и этап запустился четыре раза). Короткий однозначный ответ теперь понимается мгновенно и один раз.
export const norm = (s) => String(s || '').toLowerCase().replace(/ё/g, 'е').replace(/[^\p{L}\p{N}#№+\s-]/gu, ' ').replace(/\s+/g, ' ').trim();

const YES_HEAD = new Set(['да', 'да-да', 'делаем', 'утверждаю', 'утверждай', 'утверждаем', 'одобряю', 'одобрено', 'запускаем', 'годится', 'подходит', 'пойдет', 'вперед', 'ага', 'угу', 'ок', 'окей', 'ok', 'okay', 'yes', 'давай', 'давайте', 'делай', 'делайте', 'сделай', 'сделайте', 'согласен', 'согласна', 'подтверждаю', 'верно', 'правильно', 'запускай', 'запускайте', 'начинай', 'начинайте', 'погнали', 'поехали', '+']);
const YES_TAIL = new Set([...YES_HEAD, 'сделать', 'пожалуйста', 'все', 'так', 'конечно', 'именно', 'точно', 'тему', 'эту', 'ее', 'его', 'вот', 'ну', 'сейчас', 'и', 'хорошо', 'отлично']);
const NO_ALL = new Set(['нет', 'неа', 'не', 'no', 'отмена', 'отменяй', 'отмени', 'отменить', 'стоп', 'стой', 'нельзя', 'надо', 'нужно', 'ненадо', 'делай', 'делать', 'делайте', 'спасибо', 'пока', 'сейчас', 'ни', 'за', 'что', 'это', 'эту', 'тему']);
const CONTRA = new Set(['но', 'однако', 'только', 'кроме', 'не', 'нет', 'зачем', 'почему', 'сначала', 'подожди', 'погоди', 'стоп', 'или', 'вместо', 'лучше', 'другую', 'другое', 'другой', 'другие']);

// -> { kind: 'yes' | 'no' | null, extra }  extra: уточнение после «да,» (например «да, про 10000 шагов»)
export function classifyAnswer(text) {
  const raw = String(text || '').trim(); const w = norm(raw).split(' ').filter(Boolean);
  if (!w.length || w.length > 14) return { kind: null, extra: '' };
  if (NO_ALL.has(w[0]) && w.length <= 6 && w.every((x) => NO_ALL.has(x)) && /^(нет|неа|не|no|отмен|стоп|стой|нельзя|ни)/.test(w[0])) return { kind: 'no', extra: '' };
  if (!YES_HEAD.has(w[0])) return { kind: null, extra: '' };
  const rest = w.slice(1);
  if (rest.every((x) => YES_TAIL.has(x))) return { kind: 'yes', extra: '' };
  if (rest.length <= 12 && !rest.some((x) => CONTRA.has(x))) return { kind: 'yes', extra: raw.replace(/^\s*[\p{L}+]+[\s,.!:;—-]*/u, '').trim() };
  return { kind: null, extra: '' };
}

// «#4», «4», «тему 4», «выбираем тему #4» -> 4 (только само число, без пожеланий: с пожеланиями ответит Капитан)
export function quickPick(text) {
  const m = /^(?:(?:выбираю|выбираем|выберем|выберу|выбрать|берем|беру|бери|возьми|делаем|делай|давай|хочу|хотим|пусть будет)\s+)?(?:(?:тему|тема|темы|номер|вариант|пункт)\s+)?[#№]?\s*(\d{1,3})(?:\s+пожалуйста)?$/.exec(norm(text));
  return m ? Number(m[1]) : null;
}

// Тема названа Ником: по номеру или по заметному слову из названия
export function topicMentioned(text, id, title) {
  const t = norm(text);
  if (new RegExp(`(^|[^\\d])${Number(id)}([^\\d]|$)`).test(t)) return true;
  const stems = norm(title).split(' ').filter((x) => x.length >= 5).map((x) => x.slice(0, 5));
  return stems.some((s) => t.split(' ').some((x) => x.startsWith(s)));
}

// В ответе модели лишнее «подтвердите кнопкой»: подтверждение запрашивает сама система одной карточкой
export function stripButtonTalk(text) {
  return String(text || '').split(/(?<=[.!?…])\s+/).filter((s) => !/кнопк|подтверд|нажм/i.test(s)).join(' ').trim();
}
